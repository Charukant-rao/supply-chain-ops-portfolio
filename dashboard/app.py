"""Warehouse Ops KPI Dashboard.

A Streamlit dashboard for the first-line tech/ops team of a D2C fulfilment centre:
dispatch SLA, order turnaround, pick accuracy and inventory mismatch, with drill-downs
by failure step, channel, shift and SKU to find recurring failure patterns.

Data: synthetic sample data generated by generate_sample_data.py (not from any company).
Run:  streamlit run app.py
"""
from datetime import timedelta
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

st.set_page_config(page_title="Warehouse Ops KPI Dashboard", page_icon=":material/warehouse:", layout="wide")

DATA = Path(__file__).parent / "data"
SLA_HOURS = 24

# Palette: slate ink, amber accent (warehouse safety colour), red for breaches.
INK, MUTED, GRID = "#1E293B", "#64748B", "#E2E8F0"
ACCENT, ACCENT_SOFT = "#D97706", "#FCD9A8"
OK, BAD, NEUTRAL = "#0F766E", "#DC2626", "#CBD5E1"
STEP_COLORS = {
    "Inventory sync": "#D97706", "Allocation": "#B45309", "Label / AWB": "#0F766E",
    "Invoice": "#2563EB", "Short pick": "#7C3AED", "Manifest": "#64748B", "E-way bill": "#DB2777",
}
# Where each failure type is routed (from the triage playbook).
ROUTING = pd.DataFrame([
    ("Inventory sync", "OMS / channel integration", "Channel stock differs from WMS; sync job failed or delayed"),
    ("Allocation", "OMS support", "Orders stuck in Unfulfillable; facility or combo SKU mapping missing"),
    ("Label / AWB", "Carrier key account", "Carrier API down, PIN not serviceable, weight rule rejected"),
    ("Invoice", "ERP master data", "Missing HSN or tax rate on SKU; GSTIN/address error; IRN rejected"),
    ("Short pick", "Warehouse lead + WMS", "Physical and system stock differ; wrong putaway"),
    ("Manifest", "OMS support", "Package in wrong status; cancelled order still in manifest"),
    ("E-way bill", "Finance / tax", "Value over threshold with no e-way bill; Part B missing"),
], columns=["Failure step", "Route to", "Typical root cause"])

st.markdown(
    f"""
    <style>
      .block-container {{ padding-top: 2rem; max-width: 1280px; }}
      h1 {{ font-weight: 700; letter-spacing: -0.02em; color: {INK}; }}
      [data-testid="stMetric"] {{ background: #FFFFFF; border: 1px solid {GRID}; border-radius: 10px; padding: 14px 16px; }}
      [data-testid="stMetricLabel"] p {{ color: {MUTED}; font-size: 0.85rem; }}
      .insight {{ background: #FFF7ED; border-left: 4px solid {ACCENT}; border-radius: 6px; padding: 12px 16px; color: {INK}; margin: 4px 0 18px; line-height: 1.55; }}
      .tag {{ display: inline-block; background: #F1F5F9; color: {MUTED}; border-radius: 999px; padding: 2px 10px; font-size: 0.78rem; margin-right: 6px; }}
      .stTabs [data-baseweb="tab-list"] {{ gap: 6px; }}
      .stTabs [data-baseweb="tab"] {{ background: #F8FAFC; border-radius: 8px 8px 0 0; padding: 8px 16px; }}
    </style>
    """,
    unsafe_allow_html=True,
)


@st.cache_data
def load():
    orders = pd.read_csv(DATA / "orders.csv", parse_dates=["date"])
    picks = pd.read_csv(DATA / "picks.csv", parse_dates=["date"])
    counts = pd.read_csv(DATA / "cycle_counts.csv", parse_dates=["date"])
    orders["late"] = 1 - orders["sla_met"]
    return orders, picks, counts


def style(fig, height=340, legend=True):
    fig.update_layout(
        height=height, margin=dict(l=8, r=8, t=28, b=8), plot_bgcolor="white", paper_bgcolor="white",
        font=dict(family="Inter, -apple-system, Segoe UI, sans-serif", color=INK, size=13),
        legend=dict(orientation="h", yanchor="bottom", y=1.0, x=0, title=None, font=dict(size=12)) if legend else None,
        showlegend=legend, hoverlabel=dict(bgcolor="white", font_size=12),
    )
    fig.update_xaxes(showgrid=False, linecolor=GRID, tickfont=dict(color=MUTED))
    if any(getattr(t, "x", None) is not None and len(t.x) and hasattr(t.x[0], "year") for t in fig.data):
        fig.update_xaxes(tickformat="%b %-d")
    fig.update_yaxes(gridcolor=GRID, zeroline=False, tickfont=dict(color=MUTED))
    return fig


def show(fig, height=340, legend=True):
    """Chart title as a Streamlit heading (keeps legends clear of it), then the chart."""
    title = fig.layout.title.text
    fig.update_layout(title=dict(text=""))
    if title:
        st.markdown(f"**{title}**")
    st.plotly_chart(style(fig, height, legend), use_container_width=True)


orders, picks, counts = load()

# ---------------- Sidebar filters ----------------
with st.sidebar:
    st.markdown("### Filters")
    dmin, dmax = orders["date"].min().date(), orders["date"].max().date()
    d_from, d_to = st.date_input("Date range", (dmin, dmax), min_value=dmin, max_value=dmax)
    channels = st.multiselect("Channel", sorted(orders["channel"].unique()), default=sorted(orders["channel"].unique()))
    shifts = st.multiselect("Shift", ["Morning", "Evening"], default=["Morning", "Evening"])
    cats = st.multiselect("Category", sorted(orders["category"].unique()), default=sorted(orders["category"].unique()))
    target = st.slider("Dispatch SLA target", 90.0, 99.5, 95.0, 0.5, format="%.1f%%") / 100
    st.divider()
    st.caption(f"Dispatch SLA = carrier pickup within {SLA_HOURS} h of order creation.")
    st.caption("Sample data generated for this project; not from any company.")

mask = (
    orders["date"].dt.date.between(d_from, d_to)
    & orders["channel"].isin(channels) & orders["shift"].isin(shifts) & orders["category"].isin(cats)
)
o = orders[mask]
p = picks[picks["date"].dt.date.between(d_from, d_to) & picks["shift"].isin(shifts)]
c = counts[counts["date"].dt.date.between(d_from, d_to) & counts["category"].isin(cats)]

if o.empty:
    st.warning("No orders match these filters. Widen the date range or add a channel, shift or category.")
    st.stop()

# ---------------- Header ----------------
st.title("Warehouse Ops KPI Dashboard")
st.markdown(
    f'<span class="tag">D2C fulfilment centre · sample data</span>'
    f'<span class="tag">{d_from:%b %d} – {d_to:%b %d, %Y}</span>'
    f'<span class="tag">{len(o):,} orders</span><span class="tag">SLA target {target:.1%}</span>',
    unsafe_allow_html=True,
)

# Last 7 days vs the 7 before, for metric deltas.
end = o["date"].max()
cur = o[o["date"] > end - timedelta(days=7)]
prev = o[(o["date"] <= end - timedelta(days=7)) & (o["date"] > end - timedelta(days=14))]
pc = p[p["date"] > end - timedelta(days=7)]
pp = p[(p["date"] <= end - timedelta(days=7)) & (p["date"] > end - timedelta(days=14))]
cc = c[c["date"] > end - timedelta(days=7)]
cp = c[(c["date"] <= end - timedelta(days=7)) & (c["date"] > end - timedelta(days=14))]


def rate(df, col):
    return df[col].mean() if len(df) else float("nan")


def pick_acc(df):
    return 1 - df["pick_errors"].sum() / df["pick_lines"].sum() if df["pick_lines"].sum() else float("nan")


sla = o["sla_met"].mean()
late = o[o["late"] == 1]
steps = late["failure_step"].value_counts()
sku_stats = (
    o.groupby(["sku", "category"]).agg(orders=("order_id", "count"), late=("late", "sum")).reset_index()
)
sku_stats["late_rate"] = sku_stats["late"] / sku_stats["orders"]
top_step_by_sku = late.groupby("sku")["failure_step"].agg(lambda s: s.value_counts().index[0]).rename("main_step")
top_step_n = late.groupby("sku")["failure_step"].agg(lambda s: s.value_counts().iloc[0]).rename("late_at_main_step")
sku_stats = sku_stats.join(top_step_by_sku, on="sku").join(top_step_n, on="sku")
sku_stats = sku_stats[sku_stats["orders"] >= 30].sort_values("late_rate", ascending=False)
worst = sku_stats.iloc[0] if len(sku_stats) else None

verdict = "above" if sla >= target else "below"
insight = (
    f"<b>{sla:.1%}</b> of orders were picked up within {SLA_HOURS} h, <b>{verdict}</b> the {target:.1%} target. "
)
if len(steps):
    insight += f"<b>{steps.index[0]}</b> blocked the most late orders ({steps.iloc[0] / steps.sum():.0%}). "
if worst is not None and len(late):
    insight += (
        f"SKU <b>{worst.sku}</b> misses on <b>{worst.late_rate:.0%}</b> of its orders, "
        f"mostly at <b>{worst.main_step}</b>: a repeat pattern worth a root-cause fix."
    )
st.markdown(f'<div class="insight">{insight}</div>', unsafe_allow_html=True)

m1, m2, m3, m4, m5 = st.columns(5)
m1.metric("Orders", f"{len(o):,}", f"{len(cur) - len(prev):+,}" if len(prev) else None, delta_color="off")
d_sla = (rate(cur, "sla_met") - rate(prev, "sla_met")) * 100 if len(prev) else None
m2.metric("Dispatch SLA met", f"{sla:.1%}", f"{d_sla:+.1f} pp" if d_sla is not None else None)
d_tat = cur["tat_hours"].median() - prev["tat_hours"].median() if len(prev) else None
m3.metric("Order TAT, median", f"{o['tat_hours'].median():.1f} h",
          f"{d_tat:+.1f} h" if d_tat is not None else None, delta_color="inverse")
d_pick = (pick_acc(pc) - pick_acc(pp)) * 100 if len(pp) else None
m4.metric("Pick accuracy", f"{pick_acc(p):.2%}", f"{d_pick:+.2f} pp" if d_pick is not None else None)
d_mm = (rate(cc, "mismatch") - rate(cp, "mismatch")) * 100 if len(cp) else None
m5.metric("Inventory mismatch", f"{rate(c, 'mismatch'):.1%}",
          f"{d_mm:+.1f} pp" if d_mm is not None else None, delta_color="inverse")

st.caption("Changes compare the last 7 days of the selection with the 7 days before.")

tab1, tab2, tab3, tab4 = st.tabs(["Dispatch SLA", "Failure analysis", "Floor accuracy", "SKU drill-down"])

# ---------------- Tab 1: Dispatch SLA ----------------
with tab1:
    daily = o.groupby("date").agg(orders=("order_id", "count"), late=("late", "sum")).reset_index()
    daily["on_time"] = daily["orders"] - daily["late"]
    daily["sla"] = daily["on_time"] / daily["orders"]
    fig = go.Figure()
    fig.add_bar(x=daily["date"], y=daily["on_time"], name="On time", marker_color=NEUTRAL,
                hovertemplate="%{x|%b %d}<br>On time: %{y:,}<extra></extra>")
    fig.add_bar(x=daily["date"], y=daily["late"], name="Late", marker_color=BAD,
                hovertemplate="%{x|%b %d}<br>Late: %{y:,}<extra></extra>")
    fig.add_scatter(x=daily["date"], y=daily["sla"], name="SLA met", yaxis="y2", mode="lines+markers",
                    line=dict(color=ACCENT, width=2.5), marker=dict(size=5),
                    hovertemplate="%{x|%b %d}<br>SLA met: %{y:.1%}<extra></extra>")
    fig.add_scatter(x=[daily["date"].min(), daily["date"].max()], y=[target, target], yaxis="y2", mode="lines",
                    name=f"Target {target:.1%}", line=dict(color=INK, width=1, dash="dash"), hoverinfo="skip")
    fig.update_layout(barmode="stack", yaxis=dict(title="Orders"),
                      yaxis2=dict(overlaying="y", side="right", tickformat=".0%", range=[0.8, 1.0], showgrid=False,
                                  tickfont=dict(color=MUTED)),
                      title=dict(text="Orders per day and share dispatched within SLA", font=dict(size=15)))
    show(fig, 380)

    a, b = st.columns(2)
    with a:
        fig = go.Figure(go.Histogram(x=o["tat_hours"], xbins=dict(start=0, end=60, size=2), marker_color=NEUTRAL,
                                     hovertemplate="%{x} h: %{y:,} orders<extra></extra>"))
        fig.add_vline(x=SLA_HOURS, line=dict(color=BAD, dash="dash"),
                      annotation_text=f"{SLA_HOURS} h SLA", annotation_font_color=BAD)
        fig.update_layout(title=dict(text="Order turnaround time (order created → carrier pickup)", font=dict(size=15)),
                          xaxis_title="Hours", yaxis_title="Orders", bargap=0.08)
        show(fig, 340, legend=False)
    with b:
        heat = o.groupby(["channel", "shift"])["late"].mean().unstack("shift").reindex(columns=["Morning", "Evening"])
        heat = heat.loc[heat.mean(axis=1).sort_values(ascending=False).index]
        fig = go.Figure(go.Heatmap(z=heat.values, x=heat.columns, y=heat.index, colorscale=[[0, "#FFF7ED"], [1, BAD]],
                                   text=[[f"{v:.1%}" for v in row] for row in heat.values], texttemplate="%{text}",
                                   hovertemplate="%{y}, %{x}: %{z:.1%} late<extra></extra>", showscale=False))
        fig.update_layout(title=dict(text="Late-order rate by channel and shift", font=dict(size=15)))
        show(fig, 340, legend=False)

# ---------------- Tab 2: Failure analysis ----------------
with tab2:
    if late.empty:
        st.info("No late orders in this selection.")
    else:
        a, b = st.columns([1.1, 1])
        with a:
            par = steps.reset_index()
            par.columns = ["step", "late"]
            par["cum"] = par["late"].cumsum() / par["late"].sum()
            fig = go.Figure()
            fig.add_bar(x=par["step"], y=par["late"], marker_color=[STEP_COLORS.get(s, NEUTRAL) for s in par["step"]],
                        name="Late orders", hovertemplate="%{x}: %{y:,} late<extra></extra>")
            fig.add_scatter(x=par["step"], y=par["cum"], yaxis="y2", name="Cumulative share", mode="lines+markers",
                            line=dict(color=INK, width=2), hovertemplate="%{x}: %{y:.0%} cumulative<extra></extra>")
            fig.add_hline(y=0.8, yref="y2", line=dict(color=MUTED, dash="dot"))
            fig.update_xaxes(tickangle=-30)
            fig.update_layout(title=dict(text="Pareto: which step blocks late orders", font=dict(size=15)),
                              yaxis2=dict(overlaying="y", side="right", tickformat=".0%", range=[0, 1.05], showgrid=False))
            show(fig, 380)
        with b:
            by_day = late.groupby(["date", "failure_step"]).size().reset_index(name="late")
            fig = go.Figure()
            for s in steps.index:
                d = by_day[by_day["failure_step"] == s]
                fig.add_bar(x=d["date"], y=d["late"], name=s, marker_color=STEP_COLORS.get(s, NEUTRAL),
                            hovertemplate=f"{s}<br>%{{x|%b %d}}: %{{y}}<extra></extra>")
            fig.update_layout(barmode="stack", title=dict(text="Late orders by step, per day", font=dict(size=15)))
            show(fig, 380)
        st.markdown("##### Where each failure goes")
        route = ROUTING.merge(steps.rename("Late orders"), left_on="Failure step", right_index=True, how="left").fillna(0)
        route["Late orders"] = route["Late orders"].astype(int)
        route["Share"] = route["Late orders"] / route["Late orders"].sum() * 100
        st.dataframe(
            route.sort_values("Late orders", ascending=False), hide_index=True, use_container_width=True,
            column_config={"Share": st.column_config.ProgressColumn("Share of late orders", format="%.0f%%",
                                                                    min_value=0, max_value=100)},
        )

# ---------------- Tab 3: Floor accuracy ----------------
with tab3:
    a, b = st.columns(2)
    with a:
        pdly = p.groupby(["date", "shift"]).sum(numeric_only=True).reset_index()
        pdly["acc"] = 1 - pdly["pick_errors"] / pdly["pick_lines"]
        fig = go.Figure()
        for s, col in (("Morning", OK), ("Evening", ACCENT)):
            d = pdly[pdly["shift"] == s]
            if len(d):
                fig.add_scatter(x=d["date"], y=d["acc"], name=s, mode="lines", line=dict(color=col, width=2.5),
                                hovertemplate=f"{s}<br>%{{x|%b %d}}: %{{y:.2%}}<extra></extra>")
        fig.update_layout(title=dict(text="Pick accuracy by shift", font=dict(size=15)), yaxis=dict(tickformat=".1%"))
        show(fig, 360)
    with b:
        cat = c.groupby("category").agg(bins=("sku", "count"), mismatched=("mismatch", "sum")).reset_index()
        cat["rate"] = cat["mismatched"] / cat["bins"]
        cat = cat.sort_values("rate")
        fig = go.Figure(go.Bar(x=cat["rate"], y=cat["category"], orientation="h",
                               marker_color=[BAD if r == cat["rate"].max() else NEUTRAL for r in cat["rate"]],
                               text=[f"{r:.1%}  ({m} of {n} bins)" for r, m, n in zip(cat["rate"], cat["mismatched"], cat["bins"])],
                               textposition="outside", hovertemplate="%{y}: %{x:.1%}<extra></extra>"))
        fig.update_layout(title=dict(text="Cycle-count mismatch rate by category", font=dict(size=15)),
                          xaxis=dict(tickformat=".0%", range=[0, max(cat["rate"].max() * 1.6, 0.01)]))
        show(fig, 360, legend=False)
    var = c[c["mismatch"] == 1].assign(variance=lambda d: d["physical_qty"] - d["system_qty"])
    st.markdown("##### Latest stock mismatches to recount")
    st.dataframe(
        var.sort_values("date", ascending=False).head(12)[["date", "sku", "category", "system_qty", "physical_qty", "variance"]],
        hide_index=True, use_container_width=True,
        column_config={"date": st.column_config.DateColumn("Counted on", format="MMM D"),
                       "sku": "SKU", "category": "Category", "system_qty": "System qty", "physical_qty": "Physical qty", "variance": "Variance"},
    )

# ---------------- Tab 4: SKU drill-down ----------------
with tab4:
    st.markdown("SKUs ranked by late-order rate (30+ orders). A SKU that keeps failing at the same step "
                "points to a fixable cause: a wrong bin, a missing combo mapping, a missing HSN code.")
    flag = sku_stats.head(15).copy()
    # A SKU late on 15%+ of its orders, mostly at one step, gets a fix request in the weekly review.
    flag["Action"] = ["Raise fix request" if r >= 0.15 else "Monitor" for r in flag["late_rate"]]
    flag["late_rate"] = flag["late_rate"] * 100
    st.dataframe(
        flag[["sku", "category", "orders", "late", "late_rate", "main_step", "late_at_main_step", "Action"]],
        hide_index=True, use_container_width=True,
        column_config={
            "sku": "SKU", "category": "Category", "orders": "Orders", "late": "Late",
            "late_rate": st.column_config.ProgressColumn("Late rate", format="%.1f%%", min_value=0,
                                                         max_value=float(max(flag["late_rate"].max(), 1))),
            "main_step": "Main failure step", "late_at_main_step": "Late at that step",
        },
    )
    sel = st.selectbox("Drill into a SKU", sku_stats["sku"].tolist(), index=0)
    so = o[o["sku"] == sel]
    a, b = st.columns([1.4, 1])
    with a:
        sd = so.groupby("date").agg(orders=("order_id", "count"), late=("late", "sum")).reset_index()
        fig = go.Figure()
        fig.add_bar(x=sd["date"], y=sd["orders"] - sd["late"], name="On time", marker_color=NEUTRAL)
        fig.add_bar(x=sd["date"], y=sd["late"], name="Late", marker_color=BAD)
        fig.update_layout(barmode="stack", title=dict(text=f"{sel}: orders per day", font=dict(size=15)))
        show(fig, 320)
    with b:
        ss = so[so["late"] == 1]["failure_step"].value_counts()
        if len(ss):
            fig = go.Figure(go.Pie(labels=ss.index, values=ss.values, hole=0.55, sort=False,
                                   marker=dict(colors=[STEP_COLORS.get(s, NEUTRAL) for s in ss.index])))
            fig.update_layout(title=dict(text=f"{sel}: where its late orders got stuck", font=dict(size=15)))
            show(fig, 320)
        else:
            st.info(f"{sel} has no late orders in this selection.")
    st.download_button("Download filtered orders (CSV)", o.to_csv(index=False).encode(), "filtered_orders.csv",
                       "text/csv")
